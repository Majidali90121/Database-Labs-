--For each course, show CourseName, the number of students enrolled, and the average marks. Sort
--by average marks descending.
Select
 c.CourseName,
 Count(e.StudentID) AS NumStudents,
 AVG(e.Marks) AS AvgMarks
From Course c
Join Enrollment e ON c.CourseID=e.CourseIC
Group BY c.CourseName
ORDER BY AvgMarks DESC;


--List courses with an average marks above 80. Show CourseName and AvgMarks

Select 
 c.CourseName,
 AVG(e.Marks) AS AVG Marks
From Course c
Join Enrollment e ON c.CourseID=e.CourseID
Group BY c.CourseName
Having AVG(e.Marks)>80;

--Total fee revenue per department, assuming each enrolled student paid the course fee. Show
--Department and TotalRevenue, sorted descending

Select 
 c.Department,
 Sum(c.Fee) AS TotalRevenue
From Course c
Join Enrollment e ON c.courseID=e.CourseID
Group BY c.Department
Order BY TotalRevenue DESC;


--For each student, show how many courses they are enrolled in and their average marks. Include
--students with no enrollments
