 c.City,
 COUNT(DISTINCT c.CustID) AS NumCustomers,
 Sum(o.Quantity*p.Price) As TotalRevenue
From Customer c
JOIN OrderItem o ON p.ProdID=o.ProdID
Group BY p.ProdID,p.ProdName
