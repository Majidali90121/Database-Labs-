--Number of customers in each city. Sort by count descending
Select
 City,
 Count(*) AS NumCustomers
From Customer
Group BY City
ORDER BY NumCustomers DESC,

--Number of products in each category. Sort by count descending
Select
 Category,
 Count(*) As NumProducts
From Product
  Group BY Category
  Order BY NumProducts DESC;


--For each product category, find the average, minimum, and maximum price. Sort by average price descending
Select
 Category,
 Round(AVG(Price),2) AS AvgPrice,
 MIN(Price) AS MinPrice,
 Max(Price) AS MaxPrice
From Product
Group BY Category
Order BY AvgPrice DESC

--Total stock quantity per category. Sort by total descending.
Select 
 Category,
 Sum(StockQty) As TotalStock
From Product
Group BY Category
Order BY TotalStock;

--Number of orders placed in each year. Show Year and NumOrders, sorted by year.
Select
  YEAR(OrderDate) AS OrderYear,
  COUNT(*) AS NumOrders
From OrderItem
Group BY Year(OrderDate)
Order BY OrderYear;

--Number of orders placed each month of 2024. Show Month (1–12) and NumOrders, sorted by month
Select
 Month(OrderDate) As Month,
 COUNT(*) As NumOrders
From OrderItem
Where Year(OrderDate)=2024
Group BY MONTH(OrderDate)
ORDER BY Month;

--Find product categories where the average price is greater than 5,000
Select
  Category,
  AVG(Price) As AvgPrice
From Product
Group BY Category
Having AVG(Price)>5000;

--Find cities with more than 1 customer (exclude NULL city). (WHERE + GROUP BY + HAVING.)
Select
 City,
 Count(*) AS NumCustomers
From Customers
Where City IS NOT NULL
GROUP BY City
Having Count(*)>1
ORDER BY NumCustomers DESC;


--For each customer, count how many orders they have placed. Include customers with zero orders
Select
 c.CustID,c.CustName,
 Count(o.OrderID) AS NumOrders
From Customer c
Left JOIN OrderItem o ON c.CustID=o.CustID
Group BY c.CustID,c.CustName;

--Total quantity sold for each product. Show ProdName and TotalQty, sorted by TotalQty descending. Include
--products that have never been sold
Select 
 p.ProdID,p.ProdName,
 Sum(o.Quantity) As TotalQty
From Product p
Left JOIN OrderItem o ON p.ProdID=o.ProdID
Group BY p.ProdID,p.ProdName
ORDER BY TotalQTY DESC


--Total revenue (Quantity * Price) per product category. Sort by revenue descending
Select
  p.Category,
  Sum(o.Quantity*p.Price) AS Revenue
From OrderItem o
JOIN Product p ON o.ProdID=p.ProdID
GROUP BY p.Category
ORDER BY Revenue DESC;

--List customers whose total spend exceeds 50,000. Show CustName and TotalSpend
Select
  c.CustID,
  c.CustName,
  Sum(o.Quantity*p.Price) As TotalSpend
From Customer c
JOIN OrderItem o ON c.CustID=o.CustID
JOIN Product p ON o.ProdID=p.ProdID
Group BY C.CustID,c.CustName
Having Sum(o.Quantity*p.Price) >50000


--For each city, count the number of customers and total revenue generated by them. Include only cities with more
--than 1 customer
