--Count the total number of customers, products, and orders in the database (three separate queries or one with
--three columns).
Select
  (Select COUNT(*) From Customer) As TotalCustomers,
  (Select COUNT(*) From Product) As TotalProducts,
  (Select COUNT(*) FROM OrderItem) As TotalOrders;


--Find the cheapest and most expensive products. Show MinPrice and MaxPrice
Select
  MIN(Price) AS MinPrice,
  MAX(Price) AS MaxPrice
From Products;

--What is the average price of all products? Round to 2 decimal places.
select
  ROUND(AVG(Price),2) As AvgPrice
From Products;

--What is the total stock quantity across all products?
Select 
  Sum(StockQty) AS TotalStock
From Product

--How many distinct cities do customers live in (ignoring NULL)?
Select
  Count(DisTINCT City) AS DistinctCities
From Customer;

--How many distinct categories of products are there?
Select 
  COUNT(DISTINCT Category) As DistinctCategories
From Product;

--How many customers have a recorded city? How many do not? (Two queries.)
--Query 1

Select Count(City) As WithCity From Customer;

--Query2
Select Count(*) As WithoutCity From Customer Where City IS NULL;


--Find the earliest and latest order date in the system
Select 
  Min (OrderDate) As EarliestOrder,
  MAX(OrderDate) As LatestOrder
From OrderItem;

--Compute the total revenue from all orders. Revenue per row = Quantity * Price; total = SUM of all rows. (Hint: JOIN
--OrderItem with Product.)

Select 
  Sum(o.Quantity*p.Price) As TotalRevenue
From OrderItem o
Join Product p ON o.ProdID=p.ProID;


--Compute the average quantity per order (average of Quantity column in OrderItem). Round to 2 decimals.
Select 
  Round(AVG(Quantity),2) AS AvgQuantity
From OrderItem;

